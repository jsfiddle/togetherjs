// Renders the HTML/text templates once per locale and emits a single generated
// ES module that gets bundled into the client.
//
// This replaces the Grunt "substitute" task, which shelled out to nunjucks to
// evaluate a single `gettext()` call and then wrote one `templates-<lang>.js`
// file per locale for RequireJS to fetch at runtime. Bundling every locale
// instead costs ~40KB of HTML (before gzip) and removes both the extra request
// and the load-order race that the old togetherjs/templates.js worked around.

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const TEMPLATE_DIR = path.join(ROOT, "src/templates");
const LOCALE_DIR = path.join(TEMPLATE_DIR, "locale");

// The only template syntax the sources use is {{ gettext('...') }} / {{ gettext("...") }}.
// A real template engine was never needed for one tag with one filter.
const GETTEXT = /\{\{\s*gettext\(\s*(['"])([\s\S]*?)\1\s*\)\s*\}\}/g;

/** Unescape the JS string literal escapes that appear inside gettext() calls. */
function unescapeLiteral(s) {
  return s.replace(/\\(['"\\])/g, "$1");
}

function translate(source, translation, missing) {
  return source.replace(GETTEXT, (_match, _quote, raw) => {
    const key = unescapeLiteral(raw);
    const translated = translation[key];
    if (translated === undefined) {
      missing.add(key);
      return key;
    }
    return translated;
  });
}

export async function buildTemplates() {
  const [interfaceHtml, walkthroughHtml, helpTxt] = await Promise.all([
    fs.readFile(path.join(TEMPLATE_DIR, "interface.html"), "utf8"),
    fs.readFile(path.join(TEMPLATE_DIR, "walkthrough.html"), "utf8"),
    fs.readFile(path.join(TEMPLATE_DIR, "help.txt"), "utf8"),
  ]);

  const localeFiles = (await fs.readdir(LOCALE_DIR)).filter((f) => f.endsWith(".json"));
  const locales = {};
  const report = [];

  for (const file of localeFiles) {
    const lang = path.basename(file, ".json");
    const translation = JSON.parse(await fs.readFile(path.join(LOCALE_DIR, file), "utf8"));
    const missing = new Set();

    locales[lang] = {
      interface: translate(interfaceHtml, translation, missing),
      walkthrough: translate(walkthroughHtml, translation, missing),
      help: translate(helpTxt, translation, missing),
      names: translation.names || "",
    };

    // Locale keys ARE the English source strings, so rewording a string in
    // interface.html silently drops its translation everywhere. Say so loudly.
    if (lang !== "en-US" && missing.size) {
      report.push({ lang, missing: missing.size });
    }
  }

  const source =
    "// Generated by build/templates.mjs — do not edit.\n" +
    `export const locales = ${JSON.stringify(locales, null, 2)};\n` +
    `export const availableLocales = ${JSON.stringify(Object.keys(locales))};\n`;

  const out = path.join(TEMPLATE_DIR, "generated.js");
  const previous = await fs.readFile(out, "utf8").catch(() => null);
  if (previous !== source) {
    await fs.writeFile(out, source);
  }

  return { locales: Object.keys(locales), untranslated: report };
}
